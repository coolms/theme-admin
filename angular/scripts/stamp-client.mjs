#!/usr/bin/env node
/**
 * Writes `src/app/client.generated.ts`: the admin's client identity, `com.coolms.admin/<version>`, which every API call
 * names in `X-CoolMS-Client` (see `client-header.interceptor.ts`). The version is read from `../theme.yaml` -- the one
 * place the admin's version is kept -- so a release changes it in one place. The file is generated on
 * prebuild/pretest/prestart and not tracked, like `console.registry.ts`.
 *
 * Exit 1 when theme.yaml names no version: an identity with a made-up version would be counted as a real one.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const theme = readFileSync(join(here, '..', '..', 'theme.yaml'), 'utf8');
const found = /^version:\s*['"]?(\d+\.\d+\.\d+[0-9A-Za-z.+-]*)['"]?\s*$/m.exec(theme);
if (!found) {
    console.error('stamp-client: ../theme.yaml names no x.y.z version; nothing written');
    process.exit(1);
}

const out = join(here, '..', 'src', 'app', 'client.generated.ts');
const body = '// Generated by scripts/stamp-client.mjs from theme.yaml. Not tracked; do not edit.\n'
    + `export const ADMIN_CLIENT = 'com.coolms.admin/${found[1]}';\n`;
// Written only when it changes, so a watching build is not woken for nothing.
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) {
    writeFileSync(out, body);
}
